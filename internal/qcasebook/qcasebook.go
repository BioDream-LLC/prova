// Package qcasebook is prova's second, independent verdict engine: quorum's casebook.
//
// The rulebook (payments.cb) is written in quorum's casebook language and compiled by quorum's cbc
// compiler, which validates every combination of readings before it will emit a framework — no state
// selects two verdicts, every state selects one, and every verdict is reachable. cbc emits the
// framework as ICCMA .af (payments.af), embedded here. At run time this package does exactly what
// quorum's generated device code does: it turns the exchange into a set of present readings (the
// binding layer), attaches a closed-world attack to every absent reading, and computes the grounded
// labelling. The verdict is whichever action is accepted: pass, fail, or — when neither is — the
// evidence does not settle it.
//
// It shares nothing with prova's Go casebook (internal/verdict) except the argumentation solver: the
// rules are written in a different language, by a different construction, and compiled by a different
// program. prova runs both on every case and reports whether they agree.
package qcasebook

import (
	_ "embed"
	"fmt"
	"strconv"
	"strings"
	"sync"

	"github.com/biodream-llc/prova/internal/af"
	"github.com/biodream-llc/prova/internal/verdict"
)

//go:embed payments.cb
var sourceCB string

//go:embed payments.af
var compiledAF string

//go:embed payments.fingerprint
var fingerprint string

// Engine names this verdict engine in results and certificates.
const Engine = "quorum-casebook"

// Book is a compiled quorum casebook loaded for evaluation.
type Book struct {
	Name        string
	Version     string
	Fingerprint string
	names       []string           // argument names, index order (from the .af header)
	edges       [][2]int           // fixed attacks, zero-based
	kinds       map[[2]int]af.Kind // attack kinds for the authored attack lines
	desc        map[string]string  // name -> human description (authored arguments)
	obs         []string           // observation names, declared order
	obsIdx      map[string]int
	closedWorld int
	pass, fail  int
}

var (
	loadOnce sync.Once
	loaded   *Book
	loadErr  error
)

// Default returns the embedded payments casebook. It panics only if the embedded artefacts are
// malformed, which is a build defect caught by the package tests.
func Default() *Book {
	loadOnce.Do(func() { loaded, loadErr = Load(sourceCB, compiledAF, strings.TrimSpace(fingerprint)) })
	if loadErr != nil {
		panic("qcasebook: " + loadErr.Error())
	}
	return loaded
}

// Load parses a casebook source (for descriptions, observations and attack kinds) and the cbc-compiled
// .af (for the authoritative argument order and attack set).
func Load(cb, afText, fp string) (*Book, error) {
	b := &Book{
		Fingerprint: fp,
		kinds:       map[[2]int]af.Kind{},
		desc:        map[string]string{},
		obsIdx:      map[string]int{},
		closedWorld: -1, pass: -1, fail: -1,
	}
	index := map[string]int{}

	// .af: "#   <n> <name>" comments give the names; "<from> <to>" lines give the attacks.
	for _, line := range strings.Split(afText, "\n") {
		line = strings.TrimSpace(line)
		switch {
		case strings.HasPrefix(line, "#"):
			f := strings.Fields(strings.TrimPrefix(line, "#"))
			if len(f) == 2 {
				if n, err := strconv.Atoi(f[0]); err == nil && n == len(b.names)+1 {
					index[f[1]] = len(b.names)
					b.names = append(b.names, f[1])
				}
			}
			if len(f) >= 4 && f[0] == "GENERATED" {
				// "# GENERATED by cbc from casebook 'name' vN"
				b.Name = strings.Trim(f[len(f)-2], "'")
				b.Version = f[len(f)-1]
			}
		case strings.HasPrefix(line, "p af"), line == "":
		default:
			f := strings.Fields(line)
			if len(f) != 2 {
				continue
			}
			from, e1 := strconv.Atoi(f[0])
			to, e2 := strconv.Atoi(f[1])
			if e1 != nil || e2 != nil || from < 1 || to < 1 || from > len(b.names) || to > len(b.names) {
				return nil, fmt.Errorf("bad attack line %q", line)
			}
			b.edges = append(b.edges, [2]int{from - 1, to - 1})
		}
	}
	if len(b.names) == 0 || len(b.edges) == 0 {
		return nil, fmt.Errorf("compiled framework is empty")
	}

	// .cb: observations (in order), descriptions, and the kinds of the authored attack lines.
	for _, raw := range strings.Split(cb, "\n") {
		line := strings.TrimSpace(raw)
		if i := strings.Index(line, "#"); i >= 0 {
			line = strings.TrimSpace(line[:i])
		}
		f := strings.Fields(line)
		if len(f) < 2 {
			continue
		}
		switch f[0] {
		case "observe", "claim", "excuse", "doubt":
			if d := quoted(line); d != "" {
				b.desc[f[1]] = d
			}
			if f[0] == "observe" {
				b.obsIdx[f[1]] = len(b.obs)
				b.obs = append(b.obs, f[1])
			}
		default:
			if len(f) >= 3 {
				var k af.Kind
				switch f[1] {
				case "rebuts":
					k = af.Rebut
				case "undermines":
					k = af.Undermine
				case "undercuts":
					k = af.Undercut
				}
				if k != "" {
					for _, target := range f[2:] {
						if fi, ok := index[f[0]]; ok {
							if ti, ok := index[target]; ok {
								b.kinds[[2]int{fi, ti}] = k
							}
						}
					}
				}
			}
		}
	}
	for i, n := range b.obs {
		if index[n] != i {
			return nil, fmt.Errorf("observation %q is not argument %d in the compiled framework", n, i+1)
		}
	}
	var ok bool
	if b.closedWorld, ok = index["closed_world"]; !ok {
		return nil, fmt.Errorf("compiled framework has no closed_world argument")
	}
	if b.pass, ok = index["pass"]; !ok {
		return nil, fmt.Errorf("casebook declares no 'pass' action")
	}
	if b.fail, ok = index["fail"]; !ok {
		return nil, fmt.Errorf("casebook declares no 'fail' action")
	}
	return b, nil
}

func quoted(s string) string {
	i := strings.Index(s, "\"")
	if i < 0 {
		return ""
	}
	j := strings.Index(s[i+1:], "\"")
	if j < 0 {
		return ""
	}
	return s[i+1 : i+1+j]
}

// Observations lists the readings the casebook declares, in order.
func (b *Book) Observations() []string { return append([]string(nil), b.obs...) }

// Bind is the binding layer: it turns an exchange into the set of readings the casebook reasons over.
// All numeric, date and checksum work lives here, as quorum requires — the casebook sees booleans only.
func Bind(c verdict.Case) map[string]bool {
	r := c.Request
	ctx := func(k string) string { return strings.TrimSpace(c.Context[k]) }
	resp := c.Response
	decision := resp["decision"]
	reason := resp["rejectReason"]
	accepted := decision == "accepted"
	rejected := decision == "rejected"

	amount := strings.TrimSpace(r["Amount"])
	debits := amount != "" && ctx("debit") != "false" // returns, reversals and cancellations do not debit
	avail := ctx("availableBalance")
	balanceKnown := avail != ""
	over := debits && balanceKnown && minor(amount) > minor(avail)

	acctCcy := strings.ToUpper(ctx("accountCurrency"))
	reqCcy := strings.ToUpper(strings.TrimSpace(r["Currency"]))
	vd, sd := ctx("valueDate"), ctx("settlementDate")

	// A card is good through the end of its expiry month (Expiry is YYMM; processingDate YYYY-MM-DD).
	expired := false
	if exp, pd := strings.TrimSpace(r["Expiry"]), ctx("processingDate"); len(exp) == 4 && len(pd) >= 7 {
		expired = exp < pd[2:4]+pd[5:7]
	}
	switch strings.ToLower(ctx("accountStatus")) {
	case "closed", "blocked", "frozen", "lost", "stolen":
		expired = true // unusable, for the same reason: nothing may be accepted on it
	}
	unavailable := expired

	exceeds := func(limitKey string) bool {
		l := ctx(limitKey)
		return amount != "" && l != "" && minor(amount) > minor(l)
	}
	side := strings.ToLower(strings.TrimSpace(r["Side"]))
	short := ctx("position") != "" && (side == "sell" || side == "2") && ctx("shortSellAllowed") != "true" &&
		minor(r["OrderQty"]) > minor(ctx("position"))

	read := map[string]bool{
		"over_balance":        over,
		"ccy_mismatch":        acctCcy != "" && reqCcy != "" && acctCcy != reqCcy && ctx("fxAllowed") != "true",
		"back_valued":         vd != "" && sd != "" && vd < sd && ctx("backValueAllowed") != "true",
		"duplicate":           ctx("duplicate") == "true",
		"instruction_invalid": invalidInstruction(r),
		"account_unavailable": unavailable,
		"over_limit":          exceeds("transactionLimit"),
		"original_unknown":    ctx("originalKnown") == "false",
		"exceeds_original":    exceeds("originalAmount"),
		"already_final":       ctx("originalFinal") == "true",
		"service_closed":      ctx("marketOpen") == "false",
		"instrument_unknown":  ctx("instrumentKnown") == "false",
		"position_short":      short,
	}
	// A rejection is required when any control forbids acceptance; only then is its reason judged.
	required := false
	for _, v := range read {
		required = required || v
	}
	expect := ctx("expectReason")

	read["host_accepted"] = accepted
	read["host_rejected"] = rejected
	read["no_decision"] = decision == ""
	read["reason_given"] = reason != ""
	read["reason_wrong"] = rejected && required && expect != "" && reason != expect
	read["funds_reason"] = debits && rejected && (reason == "" || reason == "AM04" || reason == "51")
	read["balance_unknown"] = debits && !balanceKnown
	read["overdraft_unknown"] = ctx("overdraftLimit") == "unknown"
	read["cancellable"] = ctx("originalPending") == "true"
	read["status_mismatch"] = ctx("originalStatus") != "" && strings.TrimSpace(resp["reportedStatus"]) != ctx("originalStatus")
	return read
}

// Framework instantiates the casebook for a set of present readings: the fixed attacks, plus a
// closed-world attack on every absent reading (so an absent reading is decisively Out, not Undecided).
func (b *Book) Framework(present map[string]bool) af.Framework {
	var fw af.Framework
	for i, n := range b.names {
		claim := b.desc[n]
		var cites []string
		switch {
		case i < len(b.obs):
			if present[n] {
				cites = []string{"reading: " + n}
			} else {
				cites = []string{"absent: " + n}
			}
		case claim == "":
			claim = generatedClaim(n)
		}
		if claim == "" {
			claim = n
		}
		fw.Args = append(fw.Args, af.Arg{ID: n, Claim: claim, Cites: cites})
	}
	for _, e := range b.edges {
		k, ok := b.kinds[e]
		if !ok {
			k = af.Undercut // generated plumbing (gates, action wiring) attacks the inference
		}
		fw.Attacks = append(fw.Attacks, af.Attack{From: b.names[e[0]], To: b.names[e[1]], Kind: k})
	}
	for _, o := range b.obs {
		if !present[o] {
			fw.Attacks = append(fw.Attacks, af.Attack{From: b.names[b.closedWorld], To: o, Kind: af.Undermine})
		}
	}
	return fw
}

func generatedClaim(n string) string {
	switch {
	case n == "closed_world":
		return "an unreported reading is absent"
	case n == "pass":
		return "the host behaved as the rules require"
	case n == "fail":
		return "the host violated a rule"
	case strings.HasPrefix(n, "gate_no_"):
		return "no evidence of " + strings.ReplaceAll(strings.TrimPrefix(n, "gate_no_"), "_", " ")
	case strings.HasPrefix(n, "incoherent__"):
		return "the response is internally incoherent"
	}
	return strings.ReplaceAll(n, "_", " ")
}

// Prove decides a case with the quorum casebook and returns a full result: the instantiated framework,
// its grounded labelling, the outcome, and the cited chain from the pass verdict.
func (b *Book) Prove(c verdict.Case) verdict.Result {
	present := Bind(c)
	fw := b.Framework(present)
	label := fw.Grounded()
	out := verdict.Indeterminate
	switch {
	case label["fail"] == af.In:
		out = verdict.Fail
	case label["pass"] == af.In:
		out = verdict.Pass
	}
	res := verdict.Result{Outcome: out, Framework: fw, Labels: label, Chain: fw.Explain("pass")}
	if out == verdict.Indeterminate {
		for _, n := range []string{"balance_unknown", "overdraft_unknown"} {
			if present[n] {
				res.Settles = append(res.Settles, strings.TrimSuffix(n, "_unknown")+" (seed it in the scenario context)")
			}
		}
	}
	return res
}

// CrossCheck runs the quorum casebook on the case and compares it with the primary verdict.
func (b *Book) CrossCheck(c verdict.Case, primary verdict.Outcome) *verdict.CrossCheck {
	r := b.Prove(c)
	present := Bind(c)
	readings := []string{}
	for _, o := range b.obs {
		if present[o] {
			readings = append(readings, o)
		}
	}
	return &verdict.CrossCheck{
		Engine:      Engine,
		Casebook:    b.Name + " " + b.Version,
		Fingerprint: b.Fingerprint,
		Outcome:     r.Outcome,
		Agrees:      r.Outcome == primary,
		Readings:    readings,
		Chain:       r.Chain,
	}
}

// minor parses "150.00" into integer minor units (15000).
func minor(s string) int64 {
	s = strings.TrimSpace(s)
	neg := strings.HasPrefix(s, "-")
	s = strings.TrimLeft(s, "+-")
	whole, frac, _ := strings.Cut(s, ".")
	frac = (frac + "00")[:2]
	w, _ := strconv.ParseInt(whole, 10, 64)
	f, _ := strconv.ParseInt(frac, 10, 64)
	v := w*100 + f
	if neg {
		v = -v
	}
	return v
}
