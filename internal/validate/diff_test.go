package validate

import (
	_ "embed"
	"encoding/json"
	"strings"
	"testing"
)

//go:embed testdata_diff.json
var diffCorpus []byte

type diffCase struct {
	Base      string `json:"base"`
	Mut       string `json:"mut"`
	XML       string `json:"xml"`
	LxmlValid bool   `json:"lxmlValid"`
}

// TestAgreesWithLibxml2 is prova's differential schema test: a corpus of real ISO 20022 messages and
// deliberately broken mutations of them, each pre-judged by libxml2 (via lxml). prova's own schema
// validator must reach the same accept/reject verdict on every one — the same way AskISO demonstrates
// its validator agrees with the reference. The corpus is regenerated by internal/validate/gen.
func TestAgreesWithLibxml2(t *testing.T) {
	var cases []diffCase
	if err := json.Unmarshal(diffCorpus, &cases); err != nil {
		t.Fatal(err)
	}
	if len(cases) < 20 {
		t.Fatalf("thin corpus: %d cases", len(cases))
	}
	disagree := 0
	for _, c := range cases {
		rep, err := Message([]byte(c.XML), "") // schema only, no usage-guideline profile
		if err != nil {
			t.Fatalf("%s/%s: %v", c.Base, c.Mut, err)
		}
		provaValid := schemaValid(rep)
		if provaValid != c.LxmlValid {
			disagree++
			t.Errorf("%s/%s: prova schema-valid=%v, libxml2=%v; findings=%v", c.Base, c.Mut, provaValid, c.LxmlValid, rep.Findings)
		}
	}
	t.Logf("%d messages compared with libxml2, %d disagreements", len(cases), disagree)
}

// schemaValid reports whether prova found no schema (xsd.*) error. Warnings and non-schema rules are
// ignored so the comparison is strictly schema-against-schema.
func schemaValid(r Report) bool {
	for _, f := range r.Findings {
		if f.Severity == Error && strings.HasPrefix(f.Rule, "xsd.") {
			return false
		}
	}
	return true
}
